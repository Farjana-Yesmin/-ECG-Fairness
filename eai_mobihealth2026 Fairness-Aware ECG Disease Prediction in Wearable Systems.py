def train_on_subsample(data_path, subsample_fraction, random_seed, device):
    """Train model on a different random subsample"""
    # Load data with different random seed
    signals, labels, sexes, ages = load_ptbxl_data_robust(
        data_path, subsample_fraction=subsample_fraction
    )

    # Use different random seed for this subsample
    np.random.seed(random_seed)
    indices = np.random.permutation(len(signals))
    signals = signals[indices]
    labels = labels[indices]
    sexes = sexes[indices]
    ages = ages[indices]

    # Split data
    X_train, X_test, y_train, y_test, sex_train, sex_test, age_train, age_test = train_test_split(
        signals, labels, sexes, ages, test_size=0.3, stratify=labels, random_state=random_seed
    )

    train_dataset = ECGDataset(X_train, y_train, sex_train, age_train)
    test_dataset = ECGDataset(X_test, y_test, sex_test, age_test)

    train_loader = DataLoader(train_dataset, batch_size=128, shuffle=True)
    test_loader = DataLoader(test_dataset, batch_size=128)

    # Train model
    encoder = Encoder().to(device)
    classifier = Classifier().to(device)
    adv_sex = Adversary(num_classes=2).to(device)
    adv_age = Adversary(num_classes=3).to(device)

    encoder, classifier = train_model(
        encoder, classifier, adv_sex, adv_age,
        train_loader, device, lambda_val=0.3, epochs=10
    )

    # Evaluate
    encoder.eval()
    classifier.eval()

    preds, truths, sex_attrs = [], [], []
    with torch.no_grad():
        for signals, labels, sexes, ages in test_loader:
            signals = signals.permute(0, 2, 1).to(device)
            z = encoder(signals)
            pred = torch.softmax(classifier(z), dim=1)[:, 1].cpu().numpy()
            preds.extend(pred)
            truths.extend(labels.numpy())
            sex_attrs.extend(sexes.numpy())

    preds = np.array(preds)
    truths = np.array(truths)
    sex_attrs = np.array(sex_attrs)
    preds_bin = (preds > 0.5).astype(int)

    auroc = roc_auc_score(truths, preds)
    f1 = f1_score(truths, preds_bin)

    # Disparate Impact for sex
    male_pos_rate = np.mean(preds_bin[sex_attrs == 0])
    female_pos_rate = np.mean(preds_bin[sex_attrs == 1])
    di_sex = min(male_pos_rate, female_pos_rate) / max(male_pos_rate, female_pos_rate) if max(male_pos_rate, female_pos_rate) > 0 else 0

    return {
        'seed': random_seed,
        'auroc': auroc,
        'f1': f1,
        'di_sex': di_sex
    }

