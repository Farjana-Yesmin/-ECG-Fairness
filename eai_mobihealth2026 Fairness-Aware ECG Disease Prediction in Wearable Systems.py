def evaluate_intersectional(encoder, classifier, loader, device):
    """Evaluate performance on intersectional groups (sex x age)"""
    encoder.eval()
    classifier.eval()

    results = []

    # Collect predictions and attributes
    all_preds = []
    all_labels = []
    all_sex = []
    all_age = []

    with torch.no_grad():
        for signals, labels, sexes, ages in loader:
            signals = signals.permute(0, 2, 1).to(device)
            z = encoder(signals)
            pred = classifier(z)
            pred_proba = torch.softmax(pred, dim=1)[:, 1].cpu().numpy()

            all_preds.extend(pred_proba)
            all_labels.extend(labels.numpy())
            all_sex.extend(sexes.numpy())
            all_age.extend(ages.numpy())

    all_preds = np.array(all_preds)
    all_labels = np.array(all_labels)
    all_sex = np.array(all_sex)
    all_age = np.array(all_age)

    # Define intersectional groups
    sex_labels = {0: 'Male', 1: 'Female'}
    age_labels = {0: '<40', 1: '40-59', 2: '≥60'}

    # Compute metrics for each intersectional group
    for sex_val in [0, 1]:
        for age_val in [0, 1, 2]:
            mask = (all_sex == sex_val) & (all_age == age_val)

            if np.sum(mask) < 10:  # Skip groups with too few samples
                continue

            group_preds = all_preds[mask]
            group_labels = all_labels[mask]
            group_preds_bin = (group_preds > 0.5).astype(int)

            # Compute metrics
            try:
                auroc = roc_auc_score(group_labels, group_preds)
            except:
                auroc = np.nan

            acc = accuracy_score(group_labels, group_preds_bin)
            f1 = f1_score(group_labels, group_preds_bin, zero_division=0)

            results.append({
                'Sex': sex_labels[sex_val],
                'Age': age_labels[age_val],
                'Group': f"{sex_labels[sex_val]}, {age_labels[age_val]}",
                'AUROC': auroc,
                'Accuracy': acc,
                'F1': f1,
                'Sample_Size': np.sum(mask),
                'Positive_Rate': np.mean(group_labels)
            })

    return pd.DataFrame(results)

